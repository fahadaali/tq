// حساب النتيجة لفكرة واحدة من تقييماتها (1..5 لكل معيار)
function scoreIdea(ratings) {
  if (!ratings) return null;
  let weighted = 0;
  for (const c of CRITERIA) {
    const r = Number(ratings[c.id]);
    if (!r || r < 1 || r > 5) return null; // غير مكتمل
    weighted += r * c.weight;
  }
  return Math.round(weighted * 20 * 100) / 100; // نسبة من 100
}

